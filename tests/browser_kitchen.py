"""Kitchen history, closure and pickup summaries; disposable local data only."""
import argparse
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect
from browser_support import ROOT, login, open_basket, overflow

parser=argparse.ArgumentParser()
parser.add_argument('--base-url',default='http://127.0.0.1:8110')
parser.add_argument('--chromium')
args=parser.parse_args()
out=ROOT/'test-results'/'kitchen'
out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=args.chromium)
    errors=[]
    def page():
        pg=browser.new_page(viewport={'width':390,'height':844})
        pg.on('pageerror',lambda error:errors.append(str(error)))
        pg.on('dialog',lambda dialog:dialog.accept())
        pg.goto(args.base_url)
        return pg
    student=page()
    login(student,f'workspace-{uuid4().hex[:8]}@example.test',register=True)
    student.locator('[data-action=favourite][data-id=nasi-lemak]').click()
    student.get_by_role('button',name='Add Nasi lemak ayam',exact=True).click()
    student.get_by_role('button',name='Add Brown sugar milk tea',exact=True).click()
    open_basket(student)
    student.get_by_role('button',name='Choose pickup times',exact=True).click()
    student.get_by_role('button',name='Confirm all kitchen orders',exact=True).click()
    expect(student.locator('.bb-order')).to_have_count(2)
    asian=student.locator('.bb-order').filter(has=student.get_by_role('heading',name='Asian Cuisine',exact=True))
    code=asian.locator('.bb-pickup-code strong').inner_text()
    student.get_by_role('button',name='Explore',exact=True).click()
    student.locator('#kitchen-filter').select_option('asian-cuisine')
    kitchen=page()
    login(kitchen,'operator.bowl@example.test')
    kitchen.get_by_role('button',name='Menu & stock',exact=True).click()
    expect(kitchen.get_by_text('This is a sample menu.',exact=False)).to_have_count(0)
    expect(kitchen.get_by_text('Sample menu',exact=False)).to_have_count(0)
    kitchen.get_by_role('button',name='Order history',exact=True).click()
    expect(kitchen.get_by_text('No finished orders yet.',exact=True)).to_be_visible()
    kitchen.get_by_role('button',name='Close kitchen',exact=True).click()
    expect(kitchen.get_by_role('button',name='Reopen kitchen',exact=True)).to_be_visible()
    kitchen.reload()
    expect(kitchen.get_by_role('button',name='Reopen kitchen',exact=True)).to_be_visible()
    expect(student.locator('.bb-meal')).to_have_count(40,timeout=15000)
    expect(student.locator('.bb-favourite-strip')).to_have_count(0)
    expect(student.locator('#kitchen-filter')).to_have_value('all')
    session=student.evaluate("async()=> (await fetch('/api/session')).json()")
    quote=student.request.post(args.base_url+'/api/checkout/quote',data={'groups':[{'vendorId':'asian-cuisine','items':[{'itemId':'nasi-lemak','quantity':1}]}],'plan':{'mode':'pickup','budgetSen':50000}},headers={'Origin':args.base_url,'X-CSRF-Token':session['csrfToken']})
    assert quote.ok,quote.status
    assert any('paused' in reason.lower() for group in quote.json()['groups'] for reason in group['reasons']), 'Closed kitchen accepted a new quote'
    kitchen.get_by_role('button',name='Start preparing',exact=True).click()
    kitchen.get_by_role('button',name='Mark ready',exact=True).click()
    kitchen.locator('.bb-collect input[name=code]').fill(code)
    kitchen.locator('.bb-collect input[type=checkbox]').check()
    kitchen.get_by_role('button',name='Verify & complete pickup',exact=True).click()
    expect(kitchen.locator('.bb-order')).to_have_count(0)
    kitchen.get_by_role('button',name='Order history',exact=True).click()
    expect(kitchen.locator('.bb-history-table tbody tr')).to_have_count(1)
    expect(kitchen.locator('.bb-history-table')).to_contain_text('Collected')
    expect(kitchen.locator('.bb-history-table')).to_contain_text('Paid at counter')
    expect(kitchen.locator('.bb-history-table')).not_to_contain_text('Brown sugar milk tea')
    for width in [360,390,768,1440]:
        kitchen.set_viewport_size({'width':width,'height':844})
        overflow(kitchen)
    kitchen.set_viewport_size({'width':390,'height':844})
    kitchen.locator('[aria-label="Kitchen order history"]').scroll_into_view_if_needed()
    kitchen.screenshot(path=str(out/'history-mobile.png'))
    kitchen.reload()
    kitchen.get_by_role('button',name='Order history',exact=True).click()
    expect(kitchen.locator('.bb-history-table tbody tr')).to_have_count(1)
    kitchen.get_by_role('button',name='Reopen kitchen',exact=True).click()
    expect(student.locator('.bb-meal')).to_have_count(45,timeout=15000)
    expect(student.locator('.bb-favourite-strip')).to_have_count(1)
    student.get_by_role('button',name='My orders',exact=True).click()
    bobanika=student.locator('.bb-order').filter(has=student.get_by_role('heading',name='Bobanika',exact=True))
    bobanika.get_by_role('button',name='Cancel this kitchen’s order',exact=True).click()
    other=page()
    login(other,'operator.noodle@example.test')
    other.get_by_role('button',name='Order history',exact=True).click()
    expect(other.locator('.bb-history-table tbody tr')).to_have_count(1)
    expect(other.locator('.bb-history-table')).to_contain_text('Cancelled')
    expect(other.locator('.bb-history-table')).not_to_contain_text('Nasi lemak ayam')
    student.get_by_role('button',name='Availability',exact=True).click()
    expect(student.locator('.bb-kitchen-activity').first).to_contain_text('preparing')
    expect(student.locator('.bb-load-card').first).to_contain_text('Earliest estimated pickup')
    expect(student.locator('.bb-load-ranges')).to_have_count(0)
    student.evaluate('scrollTo(0,0)')
    student.screenshot(path=str(out/'availability-summary-mobile.png'))
    overflow(student)
    student.get_by_role('button',name='Explore',exact=True).click()
    expect(student.locator('.bb-meal-pickup strong').first).to_contain_text('Estimated pickup')
    student.screenshot(path=str(out/'menu-estimate-mobile.png'))
    kitchen.locator('#history-search').fill('no-such-order')
    kitchen.get_by_role('button',name='Apply filters',exact=True).click()
    expect(kitchen.locator('.bb-history-table')).to_contain_text('No orders match')
    kitchen.get_by_role('button',name='Clear filters',exact=True).click()
    expect(kitchen.locator('.bb-history-table')).to_contain_text('Collected')
    kitchen.get_by_role('combobox',name='Status',exact=True).select_option('cancelled')
    kitchen.get_by_role('button',name='Apply filters',exact=True).click()
    expect(kitchen.locator('.bb-history-table')).to_contain_text('No orders match')
    kitchen.get_by_role('button',name='Clear filters',exact=True).click()
    kitchen.get_by_label('Updated on (MYT)',exact=True).fill('2000-01-01')
    kitchen.get_by_role('button',name='Apply filters',exact=True).click()
    expect(kitchen.locator('.bb-history-table')).to_contain_text('No orders match')
    kitchen.get_by_role('button',name='Clear filters',exact=True).click()
    kitchen.get_by_role('button',name='Delays & recovery',exact=True).click()
    kitchen.locator('#incident-form select').select_option('nasi-lemak')
    kitchen.locator('#incident-form textarea').fill('Test preparation delay')
    kitchen.get_by_role('button',name='Update affected orders',exact=True).click()
    card=student.locator('.bb-meal').filter(has=student.get_by_role('heading',name='Nasi lemak ayam',exact=True))
    expect(card.locator('.bb-kitchen-state')).to_have_text('Delayed',timeout=15000)
    kitchen.get_by_role('button',name='Resolve delay',exact=True).click()
    expect(card.locator('.bb-kitchen-state')).to_have_text('Open',timeout=15000)
    student.context.set_offline(True)
    expect(card).to_contain_text('Pickup estimate unavailable',timeout=15000)
    student.context.set_offline(False)
    expect(card).to_contain_text('Estimated pickup',timeout=15000)
    assert not errors,errors
    browser.close()
    print('PASS menu notice removal, persistent closure/reopening, hidden menu/favourites, server rejection, fulfilment while closed, collected/cancelled history isolation and persistence, per-meal estimates, history filters, delay/offline states and responsive layouts.')
